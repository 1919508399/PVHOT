#!/usr/bin/env node
/* =========================================================================
 * enrich_data.js · 给 data.json 补齐 aihot 风格的派生字段
 *  - pubTime       (HH:MM)
 *  - retweetCount  (X 条转播)
 *  - user          { name, handle, color }  「同事转精选」归属
 *  - related       [ { title, link } ]      「同事件还有精选」
 * 同步写出 data_fallback.js（file:// 兜底）。
 * ========================================================================= */
const fs = require("fs");
const path = require("path");

const USERS = [
  { name: "光伏老王",   handle: "pvking_w",     color: "#2f7d5c" },
  { name: "储能观察",   handle: "storage_watch", color: "#135e6b" },
  { name: "碳索笔记",   handle: "carbon_notes",  color: "#7a4ea0" },
  { name: "光子前线",   handle: "photon_front",  color: "#b3402a" },
  { name: "硅基研究",   handle: "silicom_lab",   color: "#3a7bd5" },
  { name: "绿能周报",   handle: "green_weekly",  color: "#0e6e7c" },
  { name: "北辰能源",   handle: "polaris_neo",   color: "#c2570f" },
  { name: "链上光伏",   handle: "chain_pv",      color: "#5b8a3a" },
  { name: "度电思考",   handle: "kwh_thinker",   color: "#8a4a8e" },
  { name: "硅业分会",   handle: "silicon_assoc", color: "#1d6f8b" },
  { name: "PV-Sense",   handle: "pv_sense",      color: "#a23b3b" },
  { name: "光伏客",     handle: "pvke",          color: "#4a6b3a" },
];

const pad2 = n => String(n).padStart(2, "0");
const fmtHHMM = iso => {
  const d = new Date(iso);
  return `${pad2(d.getHours())}:${pad2(d.getMinutes())}`;
};

const data = JSON.parse(fs.readFileSync(path.join(__dirname, "data.json"), "utf8"));

// 按 category 分组
const byCat = {};
data.items.forEach((it, i) => (byCat[it.category] = byCat[it.category] || []).push({ ...it, _i: i }));

data.items.forEach((it, i) => {
  it.pubTime      = fmtHHMM(it.pubDate);
  it.retweetCount = Math.max(2, Math.round(it.heat * 0.28 + (it.title.length % 5)));
  const seed = it.id.split("").reduce((a, c) => a + c.charCodeAt(0), 0) + i;
  it.user = USERS[seed % USERS.length];
  const sibs = (byCat[it.category] || []).filter(s => s._i !== i);
  sibs.sort((a, b) =>
    (b.tags || []).filter(t => (it.tags || []).includes(t)).length -
    (a.tags || []).filter(t => (it.tags || []).includes(t)).length
  );
  it.related = sibs.slice(0, 1).map(s => ({ title: s.title, link: s.link }));
});

fs.writeFileSync(path.join(__dirname, "data.json"), JSON.stringify(data, null, 2), "utf8");
fs.writeFileSync(
  path.join(__dirname, "data_fallback.js"),
  "/* auto-generated by enrich_data.js · file:// 兜底数据 */\n" +
  "window.__PV_FALLBACK_DATA = " + JSON.stringify(data) + ";\n",
  "utf8"
);

console.log(`✅ 派生字段已写入 ${data.items.length} 条`);
console.log(`   data.json          ${fs.statSync(path.join(__dirname, "data.json")).size} B`);
console.log(`   data_fallback.js   ${fs.statSync(path.join(__dirname, "data_fallback.js")).size} B`);
console.log("   示例 user:", data.items[0].user, "· retweetCount:", data.items[0].retweetCount, "· related:", data.items[0].related.length);
